#!/usr/bin/env node
// Builds the Next.js app for the desktop bundle: a standalone server baked
// to talk to the fixed local backend port the Electron app will spawn (see
// electron/main.js), never the cloud API in .env.production.
//
// DESKTOP_BUILD is passed directly to the `next build` child process
// (rather than written to an env file) so it doesn't depend on exactly
// when Next loads .env files relative to evaluating next.config.ts.
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const { BACKEND_PORT } = require("./ports");

const repoRoot = path.join(__dirname, "..");
const envLocalPath = path.join(repoRoot, ".env.production.local");

fs.writeFileSync(
  envLocalPath,
  [
    "# Generated by electron/build-frontend.js for the desktop build — do not edit by hand.",
    `NEXT_PUBLIC_API_BASE_URL=http://127.0.0.1:${BACKEND_PORT}/api/v1`,
    "NEXT_PUBLIC_MOCK_MODE=",
    "",
  ].join("\n"),
);

const result = spawnSync("npx", ["next", "build"], {
  cwd: repoRoot,
  stdio: "inherit",
  shell: process.platform === "win32",
  env: { ...process.env, DESKTOP_BUILD: "1" },
});

process.exit(result.status ?? 1);
